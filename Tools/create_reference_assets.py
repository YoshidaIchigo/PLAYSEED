"""Import our procedural surface patterns and build reference-course materials.

Run through UnrealEditor-Cmd -run=pythonscript -script=<repository>/Tools/create_reference_assets.py.
Existing assets are preserved. Source images are generated by prepare_reference_patterns.py.
"""
from pathlib import Path
import unreal

root=Path(__file__).parent/'ReferenceTextures'
tools=unreal.AssetToolsHelpers.get_asset_tools()
edit=unreal.MaterialEditingLibrary

def expression(material,kind,x,y):return edit.create_material_expression(material,kind,x,y)
def constant(material,value,x,y):
    e=expression(material,unreal.MaterialExpressionConstant,x,y);e.set_editor_property('r',value);return e
def product(material,a,ap,b,bp,x,y):
    e=expression(material,unreal.MaterialExpressionMultiply,x,y)
    edit.connect_material_expressions(a,ap,e,'A');edit.connect_material_expressions(b,bp,e,'B');return e

for name in ['Grass','GrassEdge','Dirt','Stone','Wood','Cave','Fence','Rock','Shadow','Sky']:
    texture_path='/Game/Battlefield/T_'+name
    if not unreal.EditorAssetLibrary.does_asset_exist(texture_path):
        task=unreal.AssetImportTask();task.set_editor_property('filename',str(root/(name+'.tga')))
        task.set_editor_property('destination_path','/Game/Battlefield');task.set_editor_property('destination_name','T_'+name)
        task.set_editor_property('automated',True);task.set_editor_property('save',True)
        tools.import_asset_tasks([task])
    texture=unreal.load_asset(texture_path)
    assert texture,texture_path
    texture.set_editor_property('filter',unreal.TextureFilter.TF_NEAREST)
    texture.set_editor_property('mip_gen_settings',unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS)
    unreal.EditorAssetLibrary.save_loaded_asset(texture)
    asset_path='/Game/Battlefield/M_'+name
    if unreal.EditorAssetLibrary.does_asset_exist(asset_path):continue
    material=tools.create_asset('M_'+name,'/Game/Battlefield',unreal.Material,unreal.MaterialFactoryNew())
    material.set_editor_property('shading_model',unreal.MaterialShadingModel.MSM_UNLIT)
    material.set_editor_property('two_sided',True)
    if name=='Sky':material.set_editor_property('is_sky',True)
    sample=expression(material,unreal.MaterialExpressionTextureSample,-500,0);sample.set_editor_property('texture',texture)
    vertex=expression(material,unreal.MaterialExpressionVertexColor,-500,180)
    color=sample if name=='Sky' else product(material,sample,'RGB',vertex,'RGB',-200,0)
    edit.connect_material_property(color,'RGB' if name=='Sky' else '',unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    if name in ('Fence','Shadow'):
        material.set_editor_property('blend_mode',unreal.BlendMode.BLEND_MASKED)
        material.set_editor_property('opacity_mask_clip_value',.4)
        edit.connect_material_property(sample,'A',unreal.MaterialProperty.MP_OPACITY_MASK)
    edit.recompile_material(material);unreal.EditorAssetLibrary.save_loaded_asset(material)

if not unreal.EditorAssetLibrary.does_asset_exist('/Game/Battlefield/M_Actor'):
    material=tools.create_asset('M_Actor','/Game/Battlefield',unreal.Material,unreal.MaterialFactoryNew())
    material.set_editor_property('shading_model',unreal.MaterialShadingModel.MSM_UNLIT)
    tint=expression(material,unreal.MaterialExpressionVectorParameter,-600,0);tint.set_editor_property('parameter_name','Tint');tint.set_editor_property('default_value',unreal.LinearColor(.2,.6,.03,1))
    normal=expression(material,unreal.MaterialExpressionPixelNormalWS,-800,220)
    light=expression(material,unreal.MaterialExpressionConstant3Vector,-800,350);light.set_editor_property('constant',unreal.LinearColor(-.4,-.3,.86,1))
    dot=expression(material,unreal.MaterialExpressionDotProduct,-550,230)
    edit.connect_material_expressions(normal,'',dot,'A');edit.connect_material_expressions(light,'',dot,'B')
    clamp=expression(material,unreal.MaterialExpressionClamp,-350,230);edit.connect_material_expressions(dot,'',clamp,'Input')
    scaled=product(material,clamp,'',constant(material,.55,-350,380),'',-180,230)
    ambient=expression(material,unreal.MaterialExpressionAdd,0,230);ambient.set_editor_property('const_b',.45);edit.connect_material_expressions(scaled,'',ambient,'A')
    color=product(material,tint,'',ambient,'',160,0);edit.connect_material_property(color,'',unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    edit.recompile_material(material);unreal.EditorAssetLibrary.save_loaded_asset(material)
unreal.log('REFERENCE ASSETS PASS: ten generated patterns/materials and actor palette; no downloaded textures')
